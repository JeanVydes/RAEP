#!/usr/bin/env python3
"""Generate docs/frame-index.md from the message catalog in rfc.md (§27).

Usage: python scripts/generate_frame_index.py [--check]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def parse_catalog(rfc_text: str):
    sections = {}
    current = None
    in_catalog = False
    for line in rfc_text.splitlines():
        if line.startswith("## 27. Message Catalog"):
            in_catalog = True
            continue
        if line.startswith("## 28.") and in_catalog:
            break
        if not in_catalog:
            continue
        m = re.match(r"### 27\.(\d+)\s+(.*)", line)
        if m:
            current = "27." + m.group(1)
            sections[current] = []
            continue
        if current and line.startswith("| `"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) >= 2:
                name = cells[0].strip("` ")
                if name and not name.startswith("Enumeration"):
                    sections[current].append((name, cells[1]))
    return sections


TITLES = {
    "27.1": "Client → server",
    "27.2": "Server → client",
    "27.3": "Agent tools (called by the model, not frames)",
    "27.4": "Enumerations",
}


def render(sections) -> str:
    out = [
        "<!-- generated by scripts/generate_frame_index.py; do not edit by hand -->",
        "",
        "# Frame index",
        "",
        "Every message type from the catalog ([RFC §27](../rfc.md#27-message-catalog)),",
        "generated from the spec so the index can never drift from it. Fields marked",
        "with `*` are required. Schema: `https://raep.vyde.dev/v1/payloads/<TYPE>.json`.",
        "",
    ]
    for key in ["27.1", "27.2", "27.3", "27.4"]:
        rows = sections.get(key, [])
        if not rows:
            continue
        out.append(f"## {TITLES[key]}")
        out.append("")
        out.append("| Type | Payload | Schema |")
        out.append("| --- | --- | --- |")
        for name, payload in rows:
            if key == "27.4":
                schema = "—"
            else:
                schema = f"[schema](https://raep.vyde.dev/v1/payloads/{name}.json)"
            out.append(f"| `{name}` | {payload} | {schema} |")
        out.append("")
    return "\n".join(out)


def main() -> int:
    rfc_text = (ROOT / "rfc.md").read_text(encoding="utf-8")
    text = render(parse_catalog(rfc_text))
    target = ROOT / "docs" / "frame-index.md"
    if "--check" in sys.argv:
        ok = target.exists() and target.read_text(encoding="utf-8") == text
        if not ok:
            print("frame-index out of sync; run scripts/generate_frame_index.py")
            return 1
        print("frame-index in sync")
        return 0
    target.parent.mkdir(exist_ok=True)
    target.write_text(text, encoding="utf-8")
    print("wrote", target)
    return 0


if __name__ == "__main__":
    sys.exit(main())
